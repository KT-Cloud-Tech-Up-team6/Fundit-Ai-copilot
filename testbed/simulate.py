def main() -> None:
    base = (sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8000").rstrip("/")
    password = sys.argv[2] if len(sys.argv) > 2 else "team-only"

    print("방송 시작 대기 중… ([방송 시작]을 누르면 채팅이 흐르기 시작합니다)")
    while True:
        st = httpx.get(f"{base}/api/state", params={"password": password, "since": 0},
                       timeout=10).json()
        if st.get("started_at"):
            break
        time.sleep(2)

    print("방송 감지 — 시뮬레이션 시작")
    sent = 0
    for phase in PHASES:
        random.shuffle(phase)
        for text in phase:
            nick = random.choice(NICKS)
            try:
                r = httpx.post(f"{base}/api/chat",
                               json={"nickname": nick, "password": password, "text": text},
                               timeout=30).json()
                sent += 1
                print(f"[{sent:3d}] {nick}: {text}  -> {r.get('decision') or r.get('error')}")
            except Exception as e:
                print(f"[!] {text} -> {e}")
            time.sleep(random.uniform(3.0, 8.0))
    print(f"시나리오 종료 — 총 {sent}건 전송")


if __name__ == "__main__":
    main()
