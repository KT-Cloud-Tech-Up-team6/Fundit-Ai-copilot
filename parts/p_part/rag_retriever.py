# =========================================================
# 4. 숫자 추출
# =========================================================

def extract_numbers(text: str):
    """
    일반 숫자 추출.

    예:
    12.5cm -> 12.5
    450번 -> 450
    """

    return re.findall(
        r"\d+(?:\.\d+)?",
        text.replace(",", "")
    )


# =========================================================
# 5. 숫자 + 단위 사양 추출
# =========================================================

def extract_spec_tokens(text: str):
    """
    숫자 + 단위가 같이 있는 강한 상품 사양 표현 추출.

    예:
    12.5cm
    450RPM
    20N
    4.2kg
    870ml
    71dB
    4000mAh
    90도

    단순 숫자 '3' 같은 것은 여기서 잡지 않는다.
    """

    normalized_text = (
        text.lower()
        .replace(",", "")
        .replace("℃", "°c")
    )

    pattern = re.compile(
        r"\d+(?:\.\d+)?\s*"
        r"(?:"
        r"pa|kg|ml|mah|db|rpm|cm|mm|"
        r"hz|v|a|n|°c|도|분"
        r")",
        re.IGNORECASE
    )

    matches = pattern.findall(
        normalized_text
    )

    return [
        normalize(match)
        for match in matches
    ]


# =========================================================
# 6. 의미 있는 단어 추출
# =========================================================

def extract_words(text: str):
    words = re.findall(
        r"[가-힣a-zA-Z0-9.]+",
        text.lower()
    )

    result = []

    for word in words:
        normalized_word = normalize(
            word
        )

        if len(normalized_word) < 2:
            continue

        result.append(
            normalized_word
        )

    return result


# =========================================================
# 7. Retrieval
# =========================================================

def retrieve(
    question,
    top_k=3
):

    chunks = load_chunks()

    normalized_question = normalize(
        question
    )

    matched_rules = []


    # -----------------------------------------------------
    # 7-1. 질문에 해당하는 Retrieval Rule 탐색
    # -----------------------------------------------------

    for (
        rule_name,
        rule
    ) in RETRIEVAL_RULES.items():

        matched_keywords = []

        for keyword in rule[
            "query_keywords"
        ]:

            if (
                normalize(keyword)
                in normalized_question
            ):
                matched_keywords.append(
                    keyword
                )

        if matched_keywords:
            matched_rules.append({
                "name":
                    rule_name,

                "rule":
                    rule,

                "matched_keywords":
                    matched_keywords
            })


    # -----------------------------------------------------
    # 7-2. 강한 사양 표현 탐색
    # -----------------------------------------------------

    spec_tokens = extract_spec_tokens(
        question
    )


    # -----------------------------------------------------
    # 7-3. 무관 입력 차단
    # -----------------------------------------------------
    #
    # 다음 두 조건이 모두 없으면 검색하지 않는다.
    #
    # 1. 상품 질문 Retrieval Rule에 해당
    # 2. 숫자 + 단위 형태의 명확한 상품 사양 존재
    #
    # 예:
    #
    # python3 rag_retriever.py
    # 안녕하세요
    # 이거 좋아요?
    #
    # → []
    #
    # -----------------------------------------------------

    if (
        not matched_rules
        and not spec_tokens
    ):
        return []


    # -----------------------------------------------------
    # 질문 정보
    # -----------------------------------------------------

    question_numbers = extract_numbers(
        question
    )

    question_words = extract_words(
        question
    )


    # -----------------------------------------------------
    # 각 KB Chunk 점수 계산
    # -----------------------------------------------------

    scored = []


    for chunk in chunks:

        score = 0

        normalized_chunk = normalize(
            chunk["text"]
        )

        chunk_category = normalize(
            chunk["category"]
        )

        strong_spec_match = False


        # =================================================
        # A. Rule 기반 점수
        # =================================================

        for matched in matched_rules:

            rule = matched["rule"]


            # ---------------------------------------------
            # Category 일치
            # ---------------------------------------------

            if any(
                normalize(category)
                == chunk_category
                for category
                in rule["categories"]
            ):
                score += 10


            # ---------------------------------------------
            # Rule 핵심 단어가 KB에 존재
            # ---------------------------------------------

            for target_word in rule[
                "target_words"
            ]:

                if (
                    normalize(target_word)
                    in normalized_chunk
                ):
                    score += 6


            # ---------------------------------------------
            # 질문에서 실제로 잡힌 단어가
            # KB에도 존재
            # ---------------------------------------------

            for keyword in matched[
                "matched_keywords"
            ]:

                if (
                    normalize(keyword)
                    in normalized_chunk
                ):
                    score += 4


        # =================================================
        # B. 숫자 + 단위 정확 일치
        # =================================================
        #
        # 매우 강한 Retrieval 신호.
        #
        # 예:
        # 질문 450RPM
        # KB 450RPM
        #
        # 질문 12.5cm
        # KB 12.5cm
        #
        # =================================================

        for spec_token in spec_tokens:

            if (
                spec_token
                in normalized_chunk
            ):
                score += 20
                strong_spec_match = True


        # =================================================
        # C. 일반 숫자 직접 일치
        # =================================================
        #
        # 단독으로 Retrieval을 발생시키지는 않는다.
        # 이미 Rule 또는 사양 표현으로
        # 상품 질문임이 확인된 경우의 Ranking 보조용.
        #
        # =================================================

        if (
            matched_rules
            or strong_spec_match
        ):

            for number in question_numbers:

                if (
                    number
                    in normalized_chunk
                ):
                    score += 8


        # =================================================
        # D. 질문 단어 직접 일치
        # =================================================

        if (
            matched_rules
            or strong_spec_match
        ):

            for word in question_words:

                if (
                    word
                    in normalized_chunk
                ):
                    score += 2


        # =================================================
        # E. 단위 일치 보너스
        # =================================================

        unit_terms = [
            "rpm",
            "pa",
            "db",
            "mah",
            "kg",
            "ml",
            "cm",
            "mm"
        ]

        for unit in unit_terms:

            if (
                unit in normalized_question
                and unit in normalized_chunk
            ):
                score += 5


        # =================================================
        # F. Rule 없는 경우 추가 차단
        # =================================================
        #
        # Rule이 하나도 없었다면 반드시
        # 숫자+단위가 KB에 정확히 일치해야 한다.
        #
        # 숫자 하나 우연히 맞았다고
        # 검색 결과가 나오지 않게 한다.
        #
        # =================================================

        if (
            not matched_rules
            and not strong_spec_match
        ):
            continue


        if score > 0:
            scored.append(
                (
                    score,
                    chunk
                )
            )


    # -----------------------------------------------------
    # 점수순 정렬
    # -----------------------------------------------------

    scored.sort(
        key=lambda x: x[0],
        reverse=True
    )


    if not scored:
        return []


    highest_score = scored[0][0]


    # -----------------------------------------------------
    # 관련성이 낮은 Chunk 제거
    # -----------------------------------------------------

    filtered = []


    for (
        score,
        chunk
    ) in scored:

        minimum_score = max(
            8,
            highest_score * 0.35
        )

        if score < minimum_score:
            continue

        filtered.append(
            chunk
        )

        if len(filtered) >= top_k:
            break


    return filtered


