# 통합 재배치: KB 는 parts/p_part/data/ 에 위치 (경로만 수정, 로직 무변경)
MD_FILE = Path(__file__).parent / "data" / "product_5454434.md"


# =========================================================
# 1. MD KB 로드
# =========================================================

def load_chunks():
    text = MD_FILE.read_text(
        encoding="utf-8"
    )

    pattern = re.compile(
        r"##\s+(kb_p_\d+)\s*\|\s*(.+?)\n\n"
        r"(.*?)\n\n"
        r"-\s*strict:\s*(true|false)\n"
        r"-\s*source:\s*(.*?)(?=\n\n---|\Z)",
        re.DOTALL
    )

    chunks = []

    for match in pattern.finditer(text):
        chunks.append({
            "chunk_id":
                match.group(1).strip(),

            "category":
                match.group(2).strip(),

            "text":
                match.group(3).strip(),

            "strict":
                match.group(4).strip() == "true",

            "source":
                match.group(5).strip()
        })

    return chunks


# =========================================================
# 2. 텍스트 정규화
# =========================================================

def normalize(text: str) -> str:
    """
    표현 차이를 줄이기 위한 정규화.

    예:
    20,000Pa -> 20000pa
    90℃ -> 90°c
    12.5 cm -> 12.5cm
    """

    return (
        text.lower()
        .replace("℃", "°c")
        .replace("° c", "°c")
        .replace(",", "")
        .replace(" ", "")
    )


